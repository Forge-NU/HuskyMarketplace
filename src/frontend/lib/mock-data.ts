type GoodInput = Omit<Listing, "kind" | "seller"> & { seller: string };
const good = (l: GoodInput): Listing => ({
  ...l,
  kind: "good",
  seller: SELLERS[l.seller],
});

type ServiceInput = Pick<
  Listing,
  "id" | "title" | "cat" | "price" | "rate" | "meetup" | "posted" | "desc"
> & {
  featured?: boolean;
  seller: string;
};
const service = (l: ServiceInput): Listing => {
  const c = SERVICE_CATS.find((x) => x.id === l.cat)!;
  return {
    featured: false,
    ...l,
    kind: "service",
    obo: false,
    sub: c.name,
    icon: c.icon,
    tint: c.tint!,
    seller: SELLERS[l.seller],
  };
};

